let ACD_LANG = localStorage.getItem("acd-lang") || "ar";

function t(key) {
  const table = I18N[ACD_LANG] || I18N.ar;
  return table[key] != null ? table[key] : I18N.en[key] || key;
}

function applyLang() {
  ACD_LANG = localStorage.getItem("acd-lang") || "ar";
  const isAr = ACD_LANG === "ar";
  document.documentElement.lang = ACD_LANG;
  document.documentElement.dir = isAr ? "rtl" : "ltr";
  document.documentElement.setAttribute("data-lang", ACD_LANG);
  document.querySelectorAll("[data-i18n]").forEach((el) => {
    const key = el.getAttribute("data-i18n");
    if (el.tagName === "INPUT" || el.tagName === "TEXTAREA") {
      el.placeholder = t(key);
    } else {
      el.textContent = t(key);
    }
  });
  document.title = t("app.name") + (isAr ? " — القاموس الموحد" : " — Unified Dictionary");
}

function toggleLang() {
  const next = ACD_LANG === "ar" ? "en" : "ar";
  localStorage.setItem("acd-lang", next);
  applyLang();
  if (window.onLangChange) window.onLangChange(next);
}

document.addEventListener("DOMContentLoaded", applyLang);

/* ---- Theme (shared) ---- */
function toggleTheme() {
  const html = document.documentElement;
  const next = html.getAttribute("data-theme") === "dark" ? "light" : "dark";
  html.setAttribute("data-theme", next);
  localStorage.setItem("theme", next);
}
(function initTheme() {
  const saved = localStorage.getItem("theme");
  const prefers = window.matchMedia("(prefers-color-scheme: dark)").matches ? "dark" : "light";
  document.documentElement.setAttribute("data-theme", saved || prefers);
})();
