let ACD_LANG = localStorage.getItem("acd-lang") || "ar";

function t(key) {
  const table = I18N[ACD_LANG] || I18N.ar;
  return table[key] != null ? table[key] : I18N.en[key] || key;
}

function applyLang() {
  ACD_LANG = localStorage.getItem("acd-lang") || "ar";
  const isAr = ACD_LANG === "ar";
  document.documentElement.lang = ACD_LANG;
  document.documentElement.dir = isAr ? "rtl" : "ltr";
  document.querySelectorAll("[data-i18n]").forEach((el) => {
    const key = el.getAttribute("data-i18n");
    if (el.tagName === "INPUT" || el.tagName === "TEXTAREA") {
      el.placeholder = t(key);
    } else {
      el.textContent = t(key);
    }
  });
  document.documentElement.setAttribute("data-lang", ACD_LANG);
}

function toggleLang() {
  const next = ACD_LANG === "ar" ? "en" : "ar";
  localStorage.setItem("acd-lang", next);
  applyLang();
  if (window.onLangChange) window.onLangChange(next);
}

document.addEventListener("DOMContentLoaded", applyLang);
